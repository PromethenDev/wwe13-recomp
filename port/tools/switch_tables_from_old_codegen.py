#!/usr/bin/env python3
"""switch_tables_from_old_codegen.py <old generated dir> <new generated dir> <out.toml>

Compares the jump tables (switch statements) of two ReXGlue codegens of the same default.xex and writes
[[switch_tables]] entries for the tables the new codegen got wrong.

The old codegen (the original project's SDK 0.7.3 fork, generated/*.cpp) writes every PowerPC instruction as a
"// ..." comment, so the address of each bctr is known (function start or label + 4 per instruction). The
new codegen (SDK 0.10, port/generated/default) has no comments: its switches are matched per function, in
order. A table is written when the new switch has a different register or target list.
"""
import re
import sys
from pathlib import Path

OLD_FUNC = re.compile(r"^PPC_FUNC_IMPL\(__imp__sub_([0-9A-F]{8})\)")
NEW_FUNC = re.compile(r"^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)")
LABEL = re.compile(r"^loc_([0-9A-F]{8}):")
SWITCH = re.compile(r"^\s*switch \(ctx\.r(\d+)\.u32\) \{")
CASE_GOTO = re.compile(r"^\s*goto loc_([0-9A-F]{8});")


def parse(files, func_re, with_addresses):
    """-> {function: [(bctr_address or None, register, [targets])]}"""
    tables = {}
    for path in files:
        func = None
        addr = 0
        last_bctr = None
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        i = 0
        while i < len(lines):
            line = lines[i]
            m = func_re.match(line)
            if m:
                func = int(m.group(1), 16)
                addr = func
                tables.setdefault(func, [])
                i += 1
                continue
            m = LABEL.match(line)
            if m:
                addr = int(m.group(1), 16)
                i += 1
                continue
            if with_addresses and line.startswith("\t// "):
                if line.strip() == "// bctr":
                    last_bctr = addr
                addr += 4
                i += 1
                continue
            m = SWITCH.match(line)
            if m and func is not None:
                reg = int(m.group(1))
                targets = []
                i += 1
                while i < len(lines) and "default:" not in lines[i]:
                    g = CASE_GOTO.match(lines[i])
                    if g:
                        targets.append(int(g.group(1), 16))
                    i += 1
                tables[func].append((last_bctr if with_addresses else None, reg, targets))
                continue
            i += 1
    return tables


def main():
    old_dir, new_dir, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    old = parse(sorted(old_dir.glob("*_recomp.*.cpp")), OLD_FUNC, True)
    new = parse(sorted(new_dir.glob("*_recomp.*.cpp")), NEW_FUNC, False)
    entries = []
    unmatched = 0
    for func, old_tables in sorted(old.items()):
        new_tables = new.get(func)
        if new_tables is None:
            unmatched += len(old_tables)
            continue
        for k, (bctr, reg, targets) in enumerate(old_tables):
            if bctr is None:
                continue
            same = k < len(new_tables) and new_tables[k][1] == reg and new_tables[k][2] == targets
            if not same:
                got = len(new_tables[k][2]) if k < len(new_tables) else 0
                entries.append((func, bctr, reg, targets, got))
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# Jump tables the SDK 0.10 codegen sizes differently from the original project's codegen\n")
        f.write("# (generated by port/tools/switch_tables_from_old_codegen.py; the old tables ran in v1.5).\n\n")
        for func, bctr, reg, targets, got in entries:
            f.write(f"[[switch_tables]]  # sub_{func:08X}: {len(targets)} targets (SDK 0.10 found {got})\n")
            f.write(f"address = 0x{bctr:08X}\nregister = {reg}\n")
            f.write("labels = [" + ", ".join(f"0x{t:08X}" for t in targets) + "]\n\n")
    total = sum(len(v) for v in old.values())
    print(f"old switches: {total}, written: {len(entries)}, functions missing in the new codegen: {unmatched}")


if __name__ == "__main__":
    main()
